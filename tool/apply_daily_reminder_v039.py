def patch(path, old, new, count=1):
    f = ROOT/path
    text = f.read_text()
    if text.count(old) != count:
        raise SystemExit(f'{path}: expected {count} match(es) for {old!r}, found {text.count(old)}')
    f.write_text(text.replace(old, new))


